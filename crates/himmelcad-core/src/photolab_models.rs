//! Offline model-package verification and hardware-aware Photolab execution planning.
//!
//! This module never downloads artifacts and never changes a requested quality profile.
//! Hardware adaptation is limited to equivalent backends and resource scheduling.

use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::{hash::ObjectHash, photolab::AlignmentQualityProfile};

const MIB: u64 = 1024 * 1024;
const GIB: u64 = 1024 * MIB;

/// Compute backend encoded by a packaged model artifact.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ModelBackend {
    Cpu,
    Vulkan,
    Cuda,
}

/// On-disk representation of an offline model artifact.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum ModelArtifactFormat {
    Onnx,
    SafeTensors,
    Ncnn,
    Native,
}

/// Redistribution and attribution data pinned with an artifact.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ModelLicenseMetadata {
    pub spdx_expression: String,
    pub copyright_notice: String,
    pub license_file: String,
    pub redistribution_approved: bool,
}

/// Immutable upstream provenance retained for audits, never used for runtime downloads.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ModelSourceMetadata {
    pub repository: String,
    pub revision: String,
    pub artifact_name: String,
}

/// One backend-specific artifact in a signed offline model package.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ModelArtifactManifest {
    pub schema_version: u32,
    pub id: String,
    pub version: String,
    pub backend: ModelBackend,
    pub format: ModelArtifactFormat,
    pub sha256: ObjectHash,
    pub byte_size: u64,
    /// Shared by artifacts that implement the same model and numerical quality contract.
    pub quality_fingerprint: ObjectHash,
    pub license: ModelLicenseMetadata,
    pub source: ModelSourceMetadata,
}

/// Signature envelope generated by the offline package build pipeline.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ManifestSignature {
    pub algorithm: String,
    pub signer_key_id: String,
    pub signature: String,
}

/// Manifest plus detached signature. It is not trusted until verified locally.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SignedModelManifest {
    pub manifest: ModelArtifactManifest,
    pub signature: ManifestSignature,
}

/// Capability supplied by the native signature implementation.
///
/// Implementations must use only locally provisioned trust roots. Network-backed key lookup is
/// outside this domain contract.
pub trait OfflineManifestSignatureVerifier {
    fn verify(&self, canonical_manifest: &[u8], signature: &ManifestSignature) -> bool;
}

/// Type-safe proof that manifest metadata and its detached signature were verified.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct VerifiedModelManifest {
    signed: SignedModelManifest,
    canonical_manifest_sha256: ObjectHash,
}

impl VerifiedModelManifest {
    #[must_use]
    pub fn manifest(&self) -> &ModelArtifactManifest {
        &self.signed.manifest
    }

    #[must_use]
    pub fn signature(&self) -> &ManifestSignature {
        &self.signed.signature
    }

    #[must_use]
    pub fn canonical_manifest_sha256(&self) -> &ObjectHash {
        &self.canonical_manifest_sha256
    }
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum ManifestVerificationError {
    #[error("model manifest schema version must be non-zero")]
    InvalidSchemaVersion,
    #[error("model manifest field '{0}' must not be empty")]
    EmptyField(&'static str),
    #[error("model artifact byte size must be non-zero")]
    EmptyArtifact,
    #[error("model manifest contains an invalid SHA-256 value in '{0}'")]
    InvalidSha256(&'static str),
    #[error("model license is not approved for redistribution")]
    RedistributionNotApproved,
    #[error("failed to serialize model manifest for signature verification: {0}")]
    Serialization(String),
    #[error("model manifest signature is invalid or its signer is not trusted")]
    InvalidSignature,
}

/// Verifies a signed manifest using local trust material and returns an unforgeable wrapper.
pub fn verify_signed_manifest(
    signed: SignedModelManifest,
    verifier: &impl OfflineManifestSignatureVerifier,
) -> Result<VerifiedModelManifest, ManifestVerificationError> {
    validate_manifest_metadata(&signed)?;
    let canonical_manifest = serde_json::to_vec(&signed.manifest)
        .map_err(|error| ManifestVerificationError::Serialization(error.to_string()))?;
    if !verifier.verify(&canonical_manifest, &signed.signature) {
        return Err(ManifestVerificationError::InvalidSignature);
    }

    Ok(VerifiedModelManifest {
        canonical_manifest_sha256: ObjectHash::of_bytes(&canonical_manifest),
        signed,
    })
}

fn validate_manifest_metadata(
    signed: &SignedModelManifest,
) -> Result<(), ManifestVerificationError> {
    let manifest = &signed.manifest;
    if manifest.schema_version == 0 {
        return Err(ManifestVerificationError::InvalidSchemaVersion);
    }
    for (name, value) in [
        ("id", manifest.id.as_str()),
        ("version", manifest.version.as_str()),
        (
            "license.spdxExpression",
            manifest.license.spdx_expression.as_str(),
        ),
        (
            "license.licenseFile",
            manifest.license.license_file.as_str(),
        ),
        ("source.repository", manifest.source.repository.as_str()),
        ("source.revision", manifest.source.revision.as_str()),
        (
            "source.artifactName",
            manifest.source.artifact_name.as_str(),
        ),
        ("signature.algorithm", signed.signature.algorithm.as_str()),
        (
            "signature.signerKeyId",
            signed.signature.signer_key_id.as_str(),
        ),
        ("signature.signature", signed.signature.signature.as_str()),
    ] {
        if value.trim().is_empty() {
            return Err(ManifestVerificationError::EmptyField(name));
        }
    }
    if manifest.byte_size == 0 {
        return Err(ManifestVerificationError::EmptyArtifact);
    }
    if !is_sha256(&manifest.sha256) {
        return Err(ManifestVerificationError::InvalidSha256("sha256"));
    }
    if !is_sha256(&manifest.quality_fingerprint) {
        return Err(ManifestVerificationError::InvalidSha256(
            "qualityFingerprint",
        ));
    }
    if !manifest.license.redistribution_approved {
        return Err(ManifestVerificationError::RedistributionNotApproved);
    }
    Ok(())
}

fn is_sha256(hash: &ObjectHash) -> bool {
    hash.as_str().len() == 64 && hash.as_str().bytes().all(|byte| byte.is_ascii_hexdigit())
}

/// Stable key joining an installation record to its signed manifest.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ModelArtifactKey {
    pub id: String,
    pub version: String,
    pub backend: ModelBackend,
    pub format: ModelArtifactFormat,
}

impl From<&ModelArtifactManifest> for ModelArtifactKey {
    fn from(manifest: &ModelArtifactManifest) -> Self {
        Self {
            id: manifest.id.clone(),
            version: manifest.version.clone(),
            backend: manifest.backend,
            format: manifest.format,
        }
    }
}

/// Local installer state. Only `Verified` records are eligible for execution.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum LocalVerificationState {
    Unverified,
    Verified,
    Rejected,
}

/// Observation produced by the local package installer after reading an artifact.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LocalModelInstallation {
    pub key: ModelArtifactKey,
    /// Package-relative path. Resolution and path canonicalization belong to the installer.
    pub relative_path: String,
    pub observed_sha256: ObjectHash,
    pub observed_byte_size: u64,
    pub state: LocalVerificationState,
}

