/// One locally verified artifact in an ordered, quality-equivalent fallback chain.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlannedModelArtifact {
    pub backend: ModelBackend,
    pub format: ModelArtifactFormat,
    pub relative_path: String,
    pub sha256: ObjectHash,
    pub byte_size: u64,
}

/// Exact logical model plus backend alternatives. Every artifact shares its quality fingerprint.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlannedOfflineModel {
    pub requirement: RequiredOfflineModel,
    pub primary: PlannedModelArtifact,
    pub fallbacks: Vec<PlannedModelArtifact>,
}

/// Immutable plan persisted with a Photolab job.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct OfflineModelExecutionPlan {
    pub schema_version: u32,
    pub profile: AlignmentQualityProfile,
    pub offline_only: bool,
    pub models: Vec<PlannedOfflineModel>,
    pub resources: Vec<BackendResourcePlan>,
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum OfflineModelPlanningError {
    #[error("quality profile requires at least one offline model")]
    EmptyRequirements,
    #[error("required model id and version must not be empty")]
    InvalidRequirement,
    #[error("required model '{id}' version '{version}' has no signed manifest")]
    MissingManifest { id: String, version: String },
    #[error("required model '{id}' version '{version}' is not installed locally")]
    MissingModel { id: String, version: String },
    #[error("installed model '{id}' version '{version}' has not been locally verified")]
    UnverifiedModel { id: String, version: String },
    #[error("installed model '{id}' version '{version}' has an unexpected SHA-256 hash")]
    HashMismatch { id: String, version: String },
    #[error("installed model '{id}' version '{version}' has an unexpected byte size")]
    ByteSizeMismatch { id: String, version: String },
    #[error("model '{id}' version '{version}' does not match the required quality fingerprint")]
    QualityMismatch { id: String, version: String },
    #[error(
        "required model '{id}' version '{version}' has no verified artifact for this hardware"
    )]
    NoCompatibleBackend { id: String, version: String },
}

/// Builds a fully offline plan without substituting a different model or quality fingerprint.
pub fn plan_offline_models(
    profile: AlignmentQualityProfile,
    requirements: &[RequiredOfflineModel],
    manifests: &[VerifiedModelManifest],
    installations: &[LocalModelInstallation],
    hardware: &HardwareCapabilities,
) -> Result<OfflineModelExecutionPlan, OfflineModelPlanningError> {
    if requirements.is_empty() {
        return Err(OfflineModelPlanningError::EmptyRequirements);
    }

    let backend_order = available_backends(hardware);
    let mut planned_models = Vec::with_capacity(requirements.len());
    for requirement in requirements {
        if requirement.id.trim().is_empty() || requirement.version.trim().is_empty() {
            return Err(OfflineModelPlanningError::InvalidRequirement);
        }
        if !is_sha256(&requirement.quality_fingerprint) {
            return Err(OfflineModelPlanningError::QualityMismatch {
                id: requirement.id.clone(),
                version: requirement.version.clone(),
            });
        }

        planned_models.push(plan_required_model(
            requirement,
            manifests,
            installations,
            &backend_order,
        )?);
    }

    let resources = backend_order
        .iter()
        .copied()
        .map(|backend| resource_plan(backend, hardware))
        .collect();

    Ok(OfflineModelExecutionPlan {
        schema_version: 1,
        profile,
        offline_only: true,
        models: planned_models,
        resources,
    })
}

fn plan_required_model(
    requirement: &RequiredOfflineModel,
    manifests: &[VerifiedModelManifest],
    installations: &[LocalModelInstallation],
    backend_order: &[ModelBackend],
) -> Result<PlannedOfflineModel, OfflineModelPlanningError> {
    let logical_manifests: Vec<_> = manifests
        .iter()
        .filter(|verified| {
            let manifest = verified.manifest();
            manifest.id == requirement.id && manifest.version == requirement.version
        })
        .collect();
    if logical_manifests.is_empty() {
        return Err(OfflineModelPlanningError::MissingManifest {
            id: requirement.id.clone(),
            version: requirement.version.clone(),
        });
    }
    if logical_manifests
        .iter()
        .all(|verified| verified.manifest().quality_fingerprint != requirement.quality_fingerprint)
    {
        return Err(OfflineModelPlanningError::QualityMismatch {
            id: requirement.id.clone(),
            version: requirement.version.clone(),
        });
    }

    let mut verified_artifacts = Vec::new();
    let mut first_validation_error = None;
    for backend in backend_order {
        for verified in logical_manifests.iter().filter(|verified| {
            let manifest = verified.manifest();
            manifest.backend == *backend
                && manifest.quality_fingerprint == requirement.quality_fingerprint
        }) {
            match validate_installation(verified.manifest(), installations) {
                Ok(artifact) => verified_artifacts.push(artifact),
                Err(error) => {
                    if first_validation_error.is_none() {
                        first_validation_error = Some(error);
                    }
                }
            }
        }
    }

    let Some(primary) = verified_artifacts.first().cloned() else {
        if let Some(error) = first_validation_error {
            return Err(error);
        }
        return Err(OfflineModelPlanningError::NoCompatibleBackend {
            id: requirement.id.clone(),
            version: requirement.version.clone(),
        });
    };

    Ok(PlannedOfflineModel {
        requirement: requirement.clone(),
        primary,
        fallbacks: verified_artifacts.into_iter().skip(1).collect(),
    })
}

fn validate_installation(
    manifest: &ModelArtifactManifest,
    installations: &[LocalModelInstallation],
) -> Result<PlannedModelArtifact, OfflineModelPlanningError> {
    let expected_key = ModelArtifactKey::from(manifest);
    let Some(installation) = installations
        .iter()
        .find(|installation| installation.key == expected_key)
    else {
        return Err(OfflineModelPlanningError::MissingModel {
            id: manifest.id.clone(),
            version: manifest.version.clone(),
        });
    };
    if installation.state != LocalVerificationState::Verified {
        return Err(OfflineModelPlanningError::UnverifiedModel {
            id: manifest.id.clone(),
            version: manifest.version.clone(),
        });
    }
    if installation.observed_sha256 != manifest.sha256 {
        return Err(OfflineModelPlanningError::HashMismatch {
            id: manifest.id.clone(),
            version: manifest.version.clone(),
        });
    }
    if installation.observed_byte_size != manifest.byte_size {
        return Err(OfflineModelPlanningError::ByteSizeMismatch {
            id: manifest.id.clone(),
            version: manifest.version.clone(),
        });
    }

    Ok(PlannedModelArtifact {
        backend: manifest.backend,
        format: manifest.format,
        relative_path: installation.relative_path.clone(),
        sha256: manifest.sha256.clone(),
        byte_size: manifest.byte_size,
    })
}

fn available_backends(hardware: &HardwareCapabilities) -> Vec<ModelBackend> {
    let mut backends = Vec::with_capacity(3);
    if hardware.cuda.is_some() {
        backends.push(ModelBackend::Cuda);
    }
    if hardware.vulkan.is_some() {
        backends.push(ModelBackend::Vulkan);
    }
    backends.push(ModelBackend::Cpu);
    backends
}

fn resource_plan(backend: ModelBackend, hardware: &HardwareCapabilities) -> BackendResourcePlan {
    let usable_bytes = match backend {
        ModelBackend::Cpu => hardware.ram_bytes,
        ModelBackend::Vulkan | ModelBackend::Cuda => hardware
            .dedicated_vram_bytes
            .unwrap_or(hardware.ram_bytes / 4),
    };
    let (tile_edge_pixels, batch_size, memory_concurrency) = if usable_bytes >= 16 * GIB {
        (4_096, 8, 8)
    } else if usable_bytes >= 8 * GIB {
        (3_072, 4, 4)
    } else if usable_bytes >= 4 * GIB {
        (2_048, 2, 2)
    } else {
        (1_024, 1, 1)
    };
    let logical_cores = hardware.cpu.logical_cores.max(1);
    let max_concurrency = memory_concurrency.min(logical_cores).max(1);
    let cpu_threads_per_worker = (logical_cores / max_concurrency).max(1);

    BackendResourcePlan {
        backend,
        tile_edge_pixels,
        batch_size,
        max_concurrency,
        cpu_threads_per_worker,
    }
}

