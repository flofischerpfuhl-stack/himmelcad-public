def check(schema_path: Path, output: Path) -> int:
    with tempfile.TemporaryDirectory(prefix="himmelcad-sdk-check-") as temporary:
        expected = Path(temporary)
        generate(schema_path, expected)
        relative_paths = set(json.loads((expected / "generator-manifest.json").read_text())["outputs"])
        relative_paths.add("generator-manifest.json")
        stale = [relative for relative in sorted(relative_paths) if not (output / relative).is_file() or (output / relative).read_bytes() != (expected / relative).read_bytes()]
        if stale:
            print("stale generated Python SDK files:")
            for relative in stale:
                print(f"  {relative}")
            return 1
    print("generated Python SDK is current")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check(args.schema.resolve(), args.output.resolve())
    generate(args.schema.resolve(), args.output.resolve())
    print(f"generated HimmelCAD Python SDK in {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
