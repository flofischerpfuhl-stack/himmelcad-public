def verify_contract_sources(schema: dict[str, Any]) -> dict[str, str]:
    paths = [REPOSITORY_ROOT / relative for relative in schema["contractSources"]]
    missing = [str(path) for path in paths if not path.is_file()]
    if missing:
        raise RuntimeError(f"automation contract sources are missing: {missing!r}")
    for relative, expected in schema["contractSourcePins"].items():
        actual = sha256((REPOSITORY_ROOT / relative).read_bytes())
        if actual != expected:
            raise RuntimeError(f"canonical contract shape drifted for {relative}: expected {expected}, received {actual}; review and update the automation schema")
    mutation_source = (REPOSITORY_ROOT / "packages/@himmelcad/data/src/generated/CanonicalEntityMutation.ts").read_text()
    edit_source = (REPOSITORY_ROOT / "packages/@himmelcad/data/src/generated/CanonicalEntityEdit.ts").read_text()
    source_operations = set(re.findall(r'"operation": "([^"]+)"', mutation_source))
    schema_operations = set(schema["$defs"]["CanonicalEntityMutation"]["properties"]["operation"]["enum"])
    source_edits = set(re.findall(r'"kind": "([^"]+)"', edit_source))
    schema_edits = set(schema["$defs"]["CanonicalEntityEdit"]["properties"]["kind"]["enum"])
    if source_operations != schema_operations or source_edits != schema_edits:
        raise RuntimeError("automation mutation DTOs drifted from generated @himmelcad/data contracts")
    app_source = (REPOSITORY_ROOT / "packages/@himmelcad/app/src/canonicalProtocol.ts").read_text()
    for method in schema["methods"]["app.protocol"]["capabilityByRequestMethod"]:
        if f"'{method}'" not in app_source:
            raise RuntimeError(f"app.protocol method {method!r} is absent from the canonical TypeScript contract")
    return {str(path.relative_to(REPOSITORY_ROOT)): sha256(path.read_bytes()) for path in paths}


