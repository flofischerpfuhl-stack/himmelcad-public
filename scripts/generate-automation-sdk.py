def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def snake(name: str) -> str:
    value = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    return {"filter": "entity_filter", "schema": "schema"}.get(value, value)


def descriptor(node: dict[str, Any]) -> Any:
    if "$ref" in node:
        return ["model", node["$ref"].rsplit("/", 1)[-1]]
    if "const" in node:
        return ["scalar", type(node["const"]).__name__]
    kind = node.get("type")
    if isinstance(kind, list) and "null" in kind:
        concrete = dict(node)
        concrete["type"] = next(item for item in kind if item != "null")
        return ["nullable", descriptor(concrete)]
    if kind == "array":
        return ["tuple", descriptor(node.get("items", {}))]
    if kind == "object":
        return ["mapping"]
    return ["scalar", {"integer": "int", "number": "float", "boolean": "bool", "string": "str"}.get(kind, "Any")]


def annotation(node: dict[str, Any]) -> str:
    desc = descriptor(node)
    if desc[0] == "nullable":
        concrete = dict(node)
        concrete["type"] = next(item for item in node["type"] if item != "null")
        return f"{annotation(concrete)} | None"
    if desc[0] == "model":
        return desc[1]
    if desc[0] == "tuple":
        inner = annotation(node.get("items", {}))
        return f"tuple[{inner}, ...]"
    if desc[0] == "mapping":
        return "Mapping[str, Any]"
    return desc[1]


